const buildWaveform = (seed: number, len = 56): number[] => {
  const arr: number[] = [];
  for (let i = 0; i < len; i++) {
    const val = Math.abs(Math.sin(seed * 13.7 + i * 0.48) * 0.65 + Math.cos(i * 1.13 + seed) * 0.35);
    arr.push(Math.max(0.14, Math.min(1, Number(val.toFixed(2)))));
  }
  return arr;
};

